"""Builds js/fragments.js from tools/fragments.txt and the macOS system dictionary.

good:  the curated splits; these are the only links a puzzle is built from.
extra: other fragment pairs that happen to join into a dictionary word. Puzzles avoid
       putting both halves of one of these in the same pyramid, so there's one answer.
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
text = re.sub(r"#.*", "", (root / "tools/fragments.txt").read_text())
good = {}
for token in text.split():
    a, b = token.split("+")
    good[(a, b)] = a + b

vocab = sorted({f for pair in good for f in pair})
dictionary = {w.strip() for w in open("/usr/share/dict/words") if re.fullmatch(r"[a-z]+", w.strip())}
dictionary |= set(good.values())
extra = {}
for a in vocab:
    for b in vocab:
        if a != b and (a, b) not in good and len(a + b) >= 4 and a + b in dictionary:
            extra[(a, b)] = a + b

def pack(pairs):
    return " ".join(f"{a}+{b}" for a, b in sorted(pairs))

out = "// Generated by tools/build_fragments.py — do not edit by hand.\n"
out += "window.FRAGMENTS = " + json.dumps({"good": pack(good), "extra": pack(extra)}, indent=1) + ";\n"
(root / "js/fragments.js").write_text(out)
print(len(vocab), "fragments;", len(good), "curated words;", len(extra), "other dictionary joins blocked")
