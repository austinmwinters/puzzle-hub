"""Builds js/words.js from tools/answers.txt and the macOS system dictionary.

answers: curated common words used as daily/practice targets.
valid:   everything accepted as a guess (dictionary 5-letter words plus simple
         plurals and past tenses, which the dictionary leaves out).
"""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
answers = sorted({w for w in (root / "tools/answers.txt").read_text().split() if re.fullmatch(r"[a-z]{5}", w)})

dict_words = [w.strip() for w in open("/usr/share/dict/words") if re.fullmatch(r"[a-z]+", w.strip())]
by_len = {}
for w in dict_words:
    by_len.setdefault(len(w), set()).add(w)

valid = set(by_len.get(5, ())) | set(answers)
for w in by_len.get(4, ()):
    if not w.endswith("s"):
        valid.add(w + "s")
    if w.endswith("e"):
        valid.add(w + "d")
for w in by_len.get(3, ()):
    valid.update({w + "ed", w + "es"})

out = "// Generated by tools/build_words.py — do not edit by hand.\n"
out += "window.WORDS = {\n  answers: " + json.dumps(" ".join(answers)) + ".split(' '),\n"
out += "  valid: new Set(" + json.dumps(" ".join(sorted(valid))) + ".split(' ')),\n};\n"
(root / "js/words.js").write_text(out)
print(len(answers), "answers;", len(valid), "valid guesses")
